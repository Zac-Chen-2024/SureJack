import type { SubtitleLine } from '../types.js'

/**
 * 开头段在哪儿结束。**由字幕决定,不由排布决定。**
 *
 * ── 为什么要有这个东西 ──────────────────────────────────────────────
 * 用户想在片子烧好之后重选开头的画面,而不必重烧整条(9 分半的片子要 14 分钟)。
 * 只要开头和后半段的分界【永远落在同一个时刻】,后半段就能原样复用——
 * 只重烧开头那一两分钟,再无损拼回去。
 *
 * 关键是这个"同一个时刻"要锚在**永远不会变的东西**上。
 *
 * ── 为什么锚在字幕上 ────────────────────────────────────────────────
 * 词级时间戳在【配音完成那一刻就定死了】,之后永不改变——字幕行是从它推出来的,
 * 所以字幕的句末也是定死的。
 *
 * 反过来,"比例 × 总时长"看着也是个定值,其实不是:开头段的实际长度是
 *     min(比例 × 总长, 挑选素材的总时长)
 * 铺不满时缺口会顺延给下一段(见 compose/plan.ts 的 carry)。实测同样挑 6 个
 * 素材,换一批就从 78.0 秒变成 72.5 秒——**换素材本身就会让边界漂移**,
 * 而重选开头恰恰就是在换素材。拿它当锚点,等于把地基建在要拆的墙上。
 *
 * ── 为什么必须对齐到句末 ────────────────────────────────────────────
 * 不是为了拼接技术上正确——后半段是从母带上原样切下来的,字幕已经烧进像素,
 * 拼起来天然连续。
 *
 * 真正的理由是**观感**:让后半段从【下一句话的开头】起。切在半句话中间的话,
 * 观众会听到一句话被接缝劈开;切在句末,他只会觉得"上一句讲完了,下一句开始"。
 */

/**
 * 开头段占全片的目标比例。**15%**（2026-08-15 从 27% 调下来）。
 *
 * 和 compose/plan.ts 的 DEFAULT_RATIO[0] 是同一个数,但**故意不复用**:
 * 那个是"排布时三个桶怎么分",这个是"开头边界大概取在哪儿"。
 * 数值相同纯属自然——排布的比例以后可能因为素材结构调整,
 * 而边界一旦定了就再也不能动(动了后半段就复用不了)。
 * 各自独立,改一个不牵连另一个。
 *
 * ⚠️【改这个数只影响以后新建的项目】。每条片子的分界在配音完成那一刻
 * 算好写进 head_boundary_ms,之后一辈子用自己那一个。
 */
export const HEAD_TARGET_RATIO = 0.15

export interface HeadBoundary {
  /** 开头包含到第几句(0 起算,含这一句) */
  lineIndex: number
  /** 边界时刻:这一句结束的毫秒数 */
  endMs: number
}

/**
 * 算开头段的边界。**纯函数、确定性:同样的输入永远同样的输出。**
 *
 * 规则(用户定的):
 *   ① 算目标 = 比例 × 配音总时长
 *   ② **取大**:往后找第一句"结束时刻 ≥ 目标"的
 *   ③ 那一句的句尾就是边界
 *
 * ⚠️【取大,不取近】。取最近的话可能取到目标之前那一句,开头就比预期短。
 * 宁可多零点几秒也不能短——开头是留给观众建立第一印象的,短了不划算。
 * 实测四条真实片子,取大之后最多只比目标多 0.54 秒。
 *
 * @returns 算不出来时返回 null(没有字幕、没有配音时长)。
 *          **绝不抛**——算不出边界只意味着"这条片子不支持重选开头",
 *          不该让它连烧都烧不了。
 */
export function headBoundary (
  lines: readonly SubtitleLine[],
  totalMs: number,
  ratio: number = HEAD_TARGET_RATIO,
): HeadBoundary | null {
  if (!Number.isFinite(totalMs) || totalMs <= 0) return null
  if (lines.length === 0) return null
  if (!Number.isFinite(ratio) || ratio <= 0 || ratio >= 1) return null

  const target = totalMs * ratio
  const idx = lines.findIndex((l) => l.endMs >= target)

  /*
   * 【一句都没超过目标】= 整条片子的字幕都在目标之前结束(极短的片子,
   * 或者末尾有很长的静音)。这时候没有"后半段"可言,不支持拆分。
   */
  if (idx < 0) return null

  /*
   * 【最后一句不能当边界】。切在那儿的话后半段是空的,拼接毫无意义,
   * 而且会产出一个 0 秒的文件让 ffmpeg 报一堆看不懂的错。
   */
  if (idx >= lines.length - 1) return null

  const endMs = Math.round(lines[idx]!.endMs)
  if (endMs <= 0 || endMs >= totalMs) return null

  return { lineIndex: idx, endMs }
}
